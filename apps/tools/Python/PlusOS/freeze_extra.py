#!/usr/bin/env python3
"""freeze_extra.py - freeze the stdlib modules the PlusOS build needs to start even with no
Lib/ on disk (the encodings package) into PlusOS/frozen_extra.c."""
import marshal, os, sys
PY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODS = [  # (module name, path under Lib, is_package)
    ("encodings", "encodings/__init__.py", True),
    ("encodings.aliases", "encodings/aliases.py", False),
    ("encodings.utf_8", "encodings/utf_8.py", False),
    ("encodings.latin_1", "encodings/latin_1.py", False),
    ("encodings.ascii", "encodings/ascii.py", False),
]
out = ['/* generated by freeze_extra.py - do not edit */', '#include "Python.h"', '#include "pycore_import.h"']
tab = []
for name, rel, pkg in MODS:
    src = open(os.path.join(PY, "Lib", rel), "rb").read()
    code = compile(src, "<frozen %s>" % name, "exec", optimize=0, dont_inherit=True, module=name)
    data = marshal.dumps(code)
    var = "_PlusOS_M_" + name.replace(".", "_")
    out.append("static const unsigned char %s[] = {" % var)
    for i in range(0, len(data), 16):
        out.append("  " + ",".join(str(b) for b in data[i:i+16]) + ",")
    out.append("};")
    tab.append('    {"%s", %s, (int)sizeof(%s), %s},' % (name, var, var, "true" if pkg else "false"))
out.append("const struct _frozen _PlusOS_frozen_extra[] = {")
out += tab
out.append("    {0, 0, 0}")
out.append("};")
open(os.path.join(PY, "PlusOS", "frozen_extra.c"), "w").write("\n".join(out) + "\n")
print("froze", len(MODS), "extra modules")
