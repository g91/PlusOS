// main.cpp - p68-cc: GCC-style driver for the P68 C/C++ compiler.
//
//   p68-cc [-c|-S|-E] [-O0..-O3|-Os] [-m68000|-m68020|...] [-I dir] [-D name[=val]] -o out file.c
//
// .c/.cpp files are compiled, .S files are preprocessed and assembled, .s files assembled.
#include "cc.h"
#ifdef P68_HAVE_AS
#include "../as/assembler.h"
bool g_longJtab = false;
#endif

namespace p68 {
int tsize(const Type *t);
}
using namespace p68;

static std::string exeDir;

static bool endsWith(const std::string &s, const char *suf) {
    size_t n = strlen(suf);
    return s.size() >= n && s.compare(s.size() - n, n, suf) == 0;
}
static std::string replaceExt(const std::string &path, const char *ext) {
    size_t slash = path.find_last_of("/\\");
    size_t dot = path.find_last_of('.');
    std::string base = (dot == std::string::npos || (slash != std::string::npos && dot < slash)) ? path : path.substr(0, dot);
    if (slash != std::string::npos) base = base.substr(slash + 1);
    return base + ext;
}
static void writeFile(const std::string &path, const std::string &data) {
    FILE *f = path == "-" ? stdout : fopen(path.c_str(), "wb");
    if (!f) fatal("cannot write %s", path.c_str());
    fwrite(data.data(), 1, data.size(), f);
    if (f != stdout) fclose(f);
}

static void collectSyms(Func *f, std::set<std::string> &out) {
    auto add = [&](const Opd &o) { if (o.kind == Opd::SYM) out.insert(o.sym); };
    for (Block *b : f->blocks)
        for (Ins &i : b->ins) {
            add(i.a);
            add(i.b);
            if (i.call) {
                add(i.call->target);
                for (auto &a : i.call->args) add(a.val);
                add(i.call->retSlot);
                add(i.call->sret);
            }
            for (auto &o : i.asmOps) add(o.val);
        }
}

static bool dumpIr = false;

static std::string compileC(const std::string &path) {
    ppInit();
    SrcFile *src = loadSource(path);
    if (!src) fatal("%s: cannot open file", path.c_str());
    Token *tok = preprocess(tokenizeFile(src));
    Program *prog = parse(tok);

    // 1. IR for every function definition, in source order (enables inlining of earlier ones)
    std::vector<Func *> funcs;
    std::map<std::string, Func *> byName;
    for (Obj *g : prog->globals) {
        if (!g->isFunction || !g->isDefinition || !g->body) continue;
        Func *f = genIR(g);
        if (dumpIr) fprintf(stderr, "---- before optimisation\n%s", dumpIR(f).c_str());
        optimize(f);
        if (dumpIr) fprintf(stderr, "---- after optimisation\n%s", dumpIR(f).c_str());
        funcs.push_back(f);
        byName[f->name] = f;
    }
    // 2. reachability from externally visible definitions
    std::map<std::string, Obj *> defs;
    for (Obj *g : prog->globals)
        if (g->isDefinition) defs[g->asmName] = g;
    std::set<std::string> reach;
    std::vector<std::string> work;
    auto visit = [&](const std::string &s) {
        if (reach.insert(s).second) work.push_back(s);
    };
    for (Obj *g : prog->globals)
        if (g->isDefinition && !g->isStatic) visit(g->asmName);
    while (!work.empty()) {
        std::string s = work.back();
        work.pop_back();
        auto it = defs.find(s);
        if (it == defs.end()) continue;
        Obj *g = it->second;
        if (g->isFunction) {
            auto f = byName.find(s);
            if (f != byName.end()) {
                std::set<std::string> syms;
                collectSyms(f->second, syms);
                for (auto &x : syms) visit(x);
            }
        } else
            for (auto &r : g->relocs) visit(r.sym);
    }
    // 3. emit
    std::string out;
    out += format("| generated by p68-cc from %s\n", path.c_str());
    for (Func *f : funcs) {
        if (f->obj->isStatic && !reach.count(f->name)) continue;
        emitFunction(f, out);
    }
    // helper functions referenced by the back end (e.g. __mulsi3) are external: nothing to do
    referencedSymbols = reach;
    emitData(prog, out);
    return out;
}

static std::string preprocessAsm(const std::string &path) {
    opt.asmPreprocess = true;
    ppInit();
    SrcFile *src = loadSource(path);
    if (!src) fatal("%s: cannot open file", path.c_str());
    Token *tok = preprocess(tokenizeFile(src));
    std::string text = tokensToText(tok);
    opt.asmPreprocess = false;
    return text;
}

static void assembleTo(const std::string &asmText, const std::string &srcName, const std::string &outPath) {
#ifdef P68_HAVE_AS
    AsOptions ao;
    ao.cpu = opt.cpu;
    ao.fpu = opt.fpu;
    ao.includeDirs = opt.includeDirs;
    std::vector<unsigned char> elf;
    std::string diag;
    bool ok = assemble(asmText, srcName, ao, elf, diag);
    if (!diag.empty()) fputs(diag.c_str(), stderr);
    if (!ok) {
        if (getenv("P68_KEEP_ASM")) writeFile(outPath + ".failed.s", asmText);
        fatal("%s: assembly failed", srcName.c_str());
    }
    writeFile(outPath, std::string(elf.begin(), elf.end()));
#else
    // no built-in assembler in this build: run an external one
    std::string tmp = outPath + ".tmp.s";
    writeFile(tmp, asmText);
    const char *as = getenv("P68_AS");
    std::string cmd = format("%s -m%d -o \"%s\" \"%s\"", as ? as : "p68-as", opt.cpu, outPath.c_str(), tmp.c_str());
    int rc = system(cmd.c_str());
    if (!getenv("P68_KEEP_ASM")) remove(tmp.c_str());
    if (rc != 0) fatal("%s: assembler failed (%s)", srcName.c_str(), cmd.c_str());
#endif
}

static void writeDeps(const std::string &depFile, const std::string &target, bool phony) {
    std::string s = target + ":";
    std::set<std::string> seen;
    for (auto &d : ppDependencies) {
        if (!seen.insert(d).second) continue;
        std::string p = d;
        std::replace(p.begin(), p.end(), '\\', '/');
        s += " \\\n  " + p;
    }
    s += "\n";
    if (phony) {
        bool first = true;
        for (auto &d : seen) {
            if (first) { first = false; continue; }
            std::string p = d;
            std::replace(p.begin(), p.end(), '\\', '/');
            s += p + ":\n";
        }
    }
    writeFile(depFile, s);
}

int main(int argc, char **argv) {
    {
        std::string a0 = argv[0];
        size_t p = a0.find_last_of("/\\");
        exeDir = p == std::string::npos ? "." : a0.substr(0, p);
    }
    std::vector<std::string> inputs;
    std::string output;
    enum { LINK, COMPILE, ASM, PREPROCESS } mode = LINK;
    bool nostdinc = false, mmd = false, mp = false;
    std::string mf, mt, lang;
    for (int i = 1; i < argc; i++) {
        std::string a = argv[i];
        auto next = [&]() -> std::string {
            if (i + 1 >= argc) fatal("missing argument to %s", a.c_str());
            return argv[++i];
        };
        auto valued = [&](const char *flag, std::string &val) -> bool {
            size_t n = strlen(flag);
            if (a.compare(0, n, flag) != 0) return false;
            val = a.size() > n ? a.substr(n) : next();
            return true;
        };
        std::string v;
        if (a == "-c") mode = COMPILE;
        else if (a == "-S") mode = ASM;
        else if (a == "-E") mode = PREPROCESS;
        else if (valued("-o", v)) output = v;
        else if (a == "-isystem") opt.sysIncludeDirs.push_back(next());
        else if (a == "-idirafter") opt.afterIncludeDirs.push_back(next());
        else if (a == "-include") next();
        else if (valued("-I", v)) opt.includeDirs.push_back(v);
        else if (valued("-D", v)) opt.defines.push_back(v);
        else if (valued("-U", v)) opt.undefs.push_back(v);
        else if (a == "-O0") opt.optLevel = 0;
        else if (a == "-O" || a == "-O1") opt.optLevel = 1;
        else if (a == "-O2" || a == "-O3" || a == "-Ofast") { opt.optLevel = 2; opt.optSize = false; }
        else if (a == "-Os" || a == "-Oz") { opt.optLevel = 2; opt.optSize = true; }
        else if (a == "-m68000" || a == "-mc68000" || a == "-m68008") opt.cpu = 68000;
        else if (a == "-m68010") opt.cpu = 68010;
        else if (a == "-m68020" || a == "-mc68020" || a == "-m68020-40" || a == "-m68020-60" || a == "-mcpu32") opt.cpu = 68020;
        else if (a == "-m68030") opt.cpu = 68030;
        else if (a == "-m68040") opt.cpu = 68040;
        else if (a == "-m68060") opt.cpu = 68060;
        else if (a.compare(0, 6, "-mcpu=") == 0 || a.compare(0, 7, "-march=") == 0) {
            std::string c = a.substr(a.find('=') + 1);
            int n = atoi(c.c_str() + (c[0] == '6' ? 0 : 0));
            if (n >= 68000 && n <= 68060) opt.cpu = n == 68008 ? 68000 : n;
            else fatal("unknown cpu '%s'", c.c_str());
        } else if (a == "-m68881" || a == "-mhard-float") opt.fpu = true;
        else if (a == "-msoft-float") opt.fpu = false;
        else if (a == "-ffunction-sections") opt.functionSections = true;
        else if (a == "-mlong-jtab") g_longJtab = true;
        else if (a == "-fdata-sections") opt.dataSections = true;
        else if (a == "-ffixed-a5") opt.fixedA5 = true;
        else if (a == "-fno-fixed-a5") opt.fixedA5 = false;
        else if (a == "-fdump-ir") dumpIr = true;
        else if (a == "-nostdinc") nostdinc = true;
        else if (a == "-w") opt.warnings = false;
        else if (a == "-MMD" || a == "-MD") mmd = true;
        else if (a == "-MP") mp = true;
        else if (a == "-MF") mf = next();
        else if (a == "-MT" || a == "-MQ") mt = next();
        else if (a == "-x") lang = next();
        else if (a.compare(0, 5, "-std=") == 0) { if (a.find("++") != std::string::npos) opt.cxx = true; }
        else if (a == "-print-file-name=include") { printf("%s/../include\n", exeDir.c_str()); return 0; }
        else if (a == "-print-libgcc-file-name") { printf("%s/../lib/libp68rt.a\n", exeDir.c_str()); return 0; }
        else if (a == "--version" || a == "-v") { printf("p68-cc 0.1 (Motorola 680x0 C compiler, PlusOS toolchain)\n"); return 0; }
        else if (a == "--param" ) next();
        else if (a.compare(0, 2, "-W") == 0 || a.compare(0, 2, "-f") == 0 || a.compare(0, 2, "-g") == 0 || a.compare(0, 8, "--param=") == 0 ||
                 a.compare(0, 2, "-m") == 0 || a == "-pipe" || a == "-pedantic" || a == "-ansi") {
            // accepted for GCC command-line compatibility
        } else if (a[0] == '-' && a.size() > 1) fatal("unknown option %s", a.c_str());
        else inputs.push_back(a);
    }
    if (inputs.empty()) fatal("no input files");
    if (mode == LINK) fatal("linking through the compiler driver is not supported: compile with -c and link with p68-ld");
    if (!nostdinc || true) {
        // the compiler's own freestanding headers (stdarg.h, stdint.h, ...) are always available
        const char *inc = getenv("P68_INCLUDE");
        opt.afterIncludeDirs.push_back(inc ? inc : exeDir + "/../include");
    }
    if (inputs.size() > 1 && !output.empty()) fatal("-o with multiple input files");
    for (const std::string &in : inputs) {
        bool isCxx = endsWith(in, ".cpp") || endsWith(in, ".cc") || endsWith(in, ".cxx") || endsWith(in, ".C") || lang == "c++";
        bool isAsmCpp = endsWith(in, ".S") || lang == "assembler-with-cpp";
        bool isAsm = endsWith(in, ".s") || endsWith(in, ".asm") || lang == "assembler";
        bool savedCxx = opt.cxx;
        if (isCxx) opt.cxx = true;
        else if (lang == "c" || endsWith(in, ".c")) opt.cxx = false;
        std::string out = output;
        ppDependencies.clear();
        if (mode == PREPROCESS) {
            opt.asmPreprocess = isAsmCpp;
            ppInit();
            SrcFile *src = loadSource(in);
            if (!src) fatal("%s: cannot open file", in.c_str());
            Token *tok = preprocess(tokenizeFile(src));
            writeFile(out.empty() ? "-" : out, tokensToText(tok));
        } else {
            std::string asmText;
            if (isAsm) {
                if (!readFile(in, asmText)) fatal("%s: cannot open file", in.c_str());
            } else if (isAsmCpp)
                asmText = preprocessAsm(in);
            else
                asmText = compileC(in);
            if (mode == ASM) {
                writeFile(out.empty() ? replaceExt(in, ".s") : out, asmText);
            } else {
                if (out.empty()) out = replaceExt(in, ".o");
                assembleTo(asmText, in, out);
            }
        }
        if (mmd) {
            std::string target = !mt.empty() ? mt : (out.empty() ? replaceExt(in, ".o") : out);
            std::string dep = !mf.empty() ? mf : (out.empty() ? replaceExt(in, ".d") : (out.find_last_of('.') != std::string::npos ? out.substr(0, out.find_last_of('.')) + ".d" : out + ".d"));
            writeDeps(dep, target, mp);
        }
        opt.cxx = savedCxx;
    }
    return 0;
}
