# split_multiverse.rb - run the multiversal C-includes generator, but write one
# header per manager (QuickDraw.h, MemoryMgr.h, ...) instead of a single
# Multiverse.h, each including exactly the managers it depends on. Glue code
# the generator produces goes to one <Manager>.c per manager.
#
#   cd <Retro68>/multiversal && ruby split_multiverse.rb OUT_INCLUDE_DIR OUT_SRC_DIR
#
# Reuses the multiversal classes (make-multiverse.rb, generator.rb,
# cincludes.rb) unchanged; only the output step differs.
require 'yaml'
require 'set'
require 'fileutils'

out_inc, out_src = ARGV
abort "usage: ruby split_multiverse.rb OUT_INCLUDE_DIR OUT_SRC_DIR" unless out_inc && out_src
FileUtils.mkdir_p out_inc
FileUtils.mkdir_p out_src

# make-multiverse.rb defines the classes, then parses ARGV and generates.
# Evaluate only the class definitions.
src = File.read('make-multiverse.rb')
cut = src.index('Options = Struct.new')
abort "unexpected make-multiverse.rb layout" unless cut
eval(src[0...cut], binding, 'make-multiverse.rb')

Options = Struct.new(:output_dir, :generator)
$options = Options.new
$options.output_dir = out_inc
$options.generator = CIncludesGenerator

PRELUDE = <<~C
  /* MacPrelude.h - definitions every PlusOS ROM header starts from.
   * GENERATED by sdk/tools/split_multiverse.rb. */
  #ifndef PLUSROM_MACPRELUDE_H
  #define PLUSROM_MACPRELUDE_H
  #pragma GCC system_header
  #include <stdint.h>
  #include <stdbool.h>
  #include <stddef.h>

  #ifdef __m68k__
      #define TARGET_CPU_68K 1
      #define TARGET_CPU_PPC 0
      #define TARGET_RT_MAC_CFM 0
      #define M68K_INLINE(...) = { __VA_ARGS__ }
      #define GetCurrentArchitecture() ((int8_t)0)
  #else
      #error "the PlusOS SDK targets the 68000 (m68k-apple-macos-gcc)"
  #endif
  #ifndef TARGET_API_MAC_CARBON
  #define TARGET_API_MAC_CARBON 0
  #endif
  #ifndef OLDROUTINENAMES
  #define OLDROUTINENAMES 0
  #endif

  typedef struct RoutineDescriptor *ProcPtr;
  #define nil NULL
  #define STACK_ROUTINE_PARAMETER(n, sz) ((sz) << (kStackParameterPhase + ((n)-1) * kStackParameterWidth))

  /* Target machines. Every call is checked against the trap tables decoded
   * from the Mac Plus and Mac SE ROMs:
   *   (default)             code that runs on both: only calls in both ROMs
   *   PLUSROM_TARGET_SE     Mac SE only: SE-only calls (ADB, KeyTranslate, ...) allowed
   *   PLUSROM_TARGET_PLUS   Mac Plus only
   * Using a call the target lacks is a compile-time error that names the reason.
   * Define PLUSROM_ALLOW_UNAVAILABLE when running under a System file that adds calls. */
  #if defined(PLUSROM_ALLOW_UNAVAILABLE)
  #define PLUSROM_UNAVAILABLE(msg)
  #define PLUSROM_SE_ONLY(msg)
  #define PLUSROM_PLUS_ONLY(msg)
  #else
  #define PLUSROM_UNAVAILABLE(msg) __attribute__((unavailable(msg)))
  #if defined(PLUSROM_TARGET_SE)
  #define PLUSROM_SE_ONLY(msg)
  #define PLUSROM_PLUS_ONLY(msg) __attribute__((unavailable(msg)))
  #elif defined(PLUSROM_TARGET_PLUS)
  #define PLUSROM_SE_ONLY(msg) __attribute__((unavailable(msg)))
  #define PLUSROM_PLUS_ONLY(msg)
  #else
  #define PLUSROM_SE_ONLY(msg) __attribute__((unavailable(msg " - define PLUSROM_TARGET_SE to use it")))
  #define PLUSROM_PLUS_ONLY(msg) __attribute__((unavailable(msg " - define PLUSROM_TARGET_PLUS to use it")))
  #endif
  #endif
  #endif
C

class SplitGenerator < CIncludesGenerator
  def run(defs, out_inc, out_src)
    @functions_needing_glue = []
    File.write(File.join(out_inc, 'MacPrelude.h'), PRELUDE)
    order = {}
    defs.topsort.each_with_index { |n, i| order[n] = i }
    written = []
    defs.topsort.each do |name|
      next if name == 'MPW'                     # Executor/MPW extras, not Mac interfaces
      header = defs.headers[name]
      @impl_out = ''
      @cfmwrapper_included = false
      body = generate_header(header)
      deps = header.included.to_a.reject { |d| d == 'MPW' }.sort_by { |d| order[d] }
      guard = "PLUSROM_#{name.upcase}_H"
      text = +"/* #{name}.h - Mac Toolbox/OS interface: #{name}. GENERATED by sdk/tools/split_multiverse.rb\n"
      text << " * from Retro68's multiversal definitions; availability on the Mac Plus ROM is\n"
      text << " * marked by sdk/tools/gen_sdk.py. */\n"
      text << "#ifndef #{guard}\n#define #{guard}\n#pragma GCC system_header\n"
      text << "#include \"MacPrelude.h\"\n"
      deps.each { |d| text << "#include \"#{d}.h\"\n" }
      text << "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
      text << body                                  # carries its own #pragma pack(push, 2)/pop
      text << "\n#ifdef __cplusplus\n}\n#endif\n#endif /* #{guard} */\n"
      File.write(File.join(out_inc, "#{name}.h"), text)
      unless @impl_out.empty?
        File.write(File.join(out_src, "#{name}.glue.c"),
                   "/* #{name}.glue.c - GENERATED glue from multiversal */\n#include <plusrom/#{name}.h>\n" + @impl_out)
      end
      written << name
    end
    File.write(File.join(out_inc, 'managers.txt'), written.join("\n") + "\n")
    puts "split_multiverse: #{written.size} headers"
  end
end

defs = Defs.new(filter_key: CIncludesGenerator.filter_key)
SplitGenerator.new.run(defs, out_inc, out_src)
