def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "font8x8.c"
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in G]
    if missing:
        raise SystemExit("missing glyphs: %r" % missing)
    lines = ["/* font8x8.c - PlusOS console font, ASCII 0x20-0x7E. GENERATED by tools/genfont.py */",
             "#include <stdint.h>", "", "const uint8_t plusos_font8x8[95 * 8] = {"]
    for c in range(0x20, 0x7F):
        ch = chr(c)
        shown = ch if ch not in "\\" else "backslash"
        lines.append("    " + ", ".join("0x%02X" % b for b in G[ch]) + ",  /* %s */" % (shown if ch != "*" else "star"))
    lines += ["};", ""]
    open(out, "w").write("\n".join(lines))
    print("genfont: %d glyphs -> %s" % (len(G), out))


if __name__ == "__main__":
    main()
