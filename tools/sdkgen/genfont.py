#!/usr/bin/env python3
"""genfont.py - the PlusOS 8x8 console font (ASCII 0x20-0x7E), drawn by hand.

Glyphs use columns 0-5 (M/W use the 5 columns too) so characters get two
pixels of spacing; rows 0-6 hold capitals, row 7 is for descenders.
Writes a C array: const uint8_t plusos_font8x8[95*8], 1 bits = black.
"""
import sys

G = {}


def g(ch, *rows):
    rows = list(rows) + ["........"] * (8 - len(rows))
    assert len(rows) == 8, ch
    G[ch] = [sum(1 << (7 - i) for i, c in enumerate(r.ljust(8)[:8]) if c == "#") for r in rows]


